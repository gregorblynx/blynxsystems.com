// Generates the staging variant of the canonical Apps Script lead-intake
// source (integrations/google-apps-script.gs), per docs/plans/
// blynx-homepage-restructure.md §12.3 "minimum-divergence rule": the staging
// script must be the exact production logic with only two documented literal
// substitutions — nothing else may differ, or staging tests stop meaning
// anything.
//
// This does NOT create the staging Google Sheet or deploy anything — those
// steps require one-time, human-driven interactive Google authorization (see
// §12.3 "One-time setup"). Run this after editing the canonical .gs file to
// regenerate integrations/google-apps-script.staging.gs, then paste that
// file's contents into the staging project's Apps Script editor.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const sourcePath = path.join(root, "integrations", "google-apps-script.gs");
const outputPath = path.join(root, "integrations", "google-apps-script.staging.gs");

const SUBJECT_FIND = "subject: `New BLYNX ${formType} lead: ${business} (${name})`,";
const SUBJECT_REPLACE = "subject: `[STAGING] BLYNX Lead Test — ${formType}: ${business} (${name})`,";

function run() {
  const canonical = fs.readFileSync(sourcePath, "utf8");

  if (!canonical.includes(SUBJECT_FIND)) {
    throw new Error(
      "google-apps-script.gs no longer contains the expected email-subject line — " +
        "update SUBJECT_FIND/SUBJECT_REPLACE in this script to match, then re-run."
    );
  }

  const staging =
    `/**\n * STAGING VARIANT — generated by scripts/build-staging-apps-script.js.\n` +
    ` * Do not hand-edit; edit integrations/google-apps-script.gs and re-run the generator.\n` +
    ` *\n` +
    ` * The ONLY differences from production, per the minimum-divergence rule\n` +
    ` * (docs/plans/blynx-homepage-restructure.md §12.3):\n` +
    ` *   - Email subject is prefixed "[STAGING] BLYNX Lead Test —" instead of "New BLYNX".\n` +
    ` *   - NOTIFY_EMAIL is intentionally unchanged (same inbox as production).\n` +
    ` * Validation, sanitisation, honeypot handling and appendRow() behaviour are\n` +
    ` * byte-identical to production.\n` +
    ` *\n` +
    ` * One-time setup (human-assisted, requires interactive Google authorization):\n` +
    ` * 1. Create spreadsheet "BLYNX Leads (Staging)".\n` +
    ` * 2. Extensions -> Apps Script. Paste this file's contents (below this header).\n` +
    ` * 3. Deploy -> New deployment -> type "Web app". Execute as: Me. Who has access: Anyone.\n` +
    ` * 4. Authorize the Sheets + Mail scopes when prompted.\n` +
    ` * 5. Copy the Web App URL (ends in /exec) and set it as the Preview-only\n` +
    ` *    LEAD_WEBHOOK_URL: vercel env add LEAD_WEBHOOK_URL preview\n` +
    ` * 6. Verify: GET <staging /exec> returns "BLYNX lead intake is running."\n` +
    ` */\n\n` +
    canonical.replace(SUBJECT_FIND, SUBJECT_REPLACE);

  fs.writeFileSync(outputPath, staging);
  console.log(`Wrote ${path.relative(root, outputPath)}`);
}

run();
